// Reading and writing SIPNET's text formats (sipnet.in, .param, .out)

// Model option flags, as named in sipnet.in; defaults from src/common/context.c
export const FLAGS = [
  { name: 'EVENTS', label: 'Events', def: 1, help: 'Apply agronomic events from events.in' },
  { name: 'GDD', label: 'GDD phenology', def: 1, help: 'Use growing degree days to determine leaf growth' },
  { name: 'GROWTH_RESP', label: 'Growth respiration', def: 0, help: 'Model growth respiration explicitly' },
  { name: 'LEAF_WATER', label: 'Leaf water', def: 0, help: 'Calculate a leaf water pool and evaporate from it' },
  { name: 'LITTER_POOL', label: 'Litter pool', def: 0, help: 'Litter pool in addition to the soil carbon pool' },
  { name: 'MICROBES', label: 'Microbes', def: 0, help: 'Enable microbe modeling' },
  { name: 'NITROGEN_CYCLE', label: 'Nitrogen cycle', def: 0, help: 'Enable modeling of the nitrogen cycle' },
  { name: 'SNOW', label: 'Snow', def: 1, help: 'Track snowpack rather than treating all precipitation as liquid' },
  { name: 'SOIL_PHENOL', label: 'Soil-temperature phenology', def: 0, help: 'Use soil temperature to determine leaf growth' },
  { name: 'WATER_HRESP', label: 'Water-limited Rh', def: 1, help: 'Soil moisture affects heterotrophic respiration' },
];

// Same normalization SIPNET uses for config names (nameToKey in context.c)
export const normKey = (name) => name.replace(/[^A-Za-z0-9]/g, '').toLowerCase();

export function defaultFlags() {
  return Object.fromEntries(FLAGS.map((f) => [f.name, f.def]));
}

// Mirrors validateContext() in context.c, so we can warn before running
export function flagConflicts(flags) {
  const errs = [];
  if (flags.SOIL_PHENOL && flags.GDD) errs.push('Soil-temperature phenology and GDD phenology cannot both be on');
  if (flags.EVENTS && flags.MICROBES) errs.push('Events and microbes cannot both be on');
  if (flags.NITROGEN_CYCLE && flags.MICROBES) errs.push('Nitrogen cycle and microbes cannot both be on');
  return errs;
}

// Strip '!' comments; returns trimmed content
const stripComment = (line) => line.replace(/!.*/, '').trim();

// Parse model flags out of a sipnet.in; unknown/unset flags keep defaults
export function parseConfigFlags(text) {
  const flags = defaultFlags();
  const byKey = Object.fromEntries(FLAGS.map((f) => [normKey(f.name), f.name]));
  for (const raw of text.split(/\r?\n/)) {
    const line = stripComment(raw);
    if (!line) continue;
    const [name, value] = line.split(/[\s=:]+/);
    const flag = byKey[normKey(name)];
    if (flag && value !== undefined) flags[flag] = parseInt(value, 10) ? 1 : 0;
  }
  return flags;
}

export function buildConfig(flags) {
  const lines = [
    '! Generated by the SIPNET WebAssembly runner',
    'FILE_NAME = sipnet',
    'DO_MAIN_OUTPUT = 1',
    'PRINT_HEADER = 1',
    'DO_SINGLE_OUTPUTS = 0',
    'DUMP_CONFIG = 1',
  ];
  for (const f of FLAGS) lines.push(`${f.name} = ${flags[f.name] ? 1 : 0}`);
  return lines.join('\n') + '\n';
}

// .param format: "name value [estimated min max sigma]" with '!' comments.
// Returns the raw lines plus, for each parameter, its line index and value.
const PARAM_LINE = /^(\s*)(\S+)(\s+)([^\s!]+)(.*)$/;

export function parseParamFile(text) {
  const lines = text.split(/\r?\n/);
  const params = [];
  lines.forEach((raw, i) => {
    if (!stripComment(raw)) return;
    const m = raw.match(PARAM_LINE);
    if (m) params.push({ name: m[2], value: m[4], line: i });
  });
  return { lines, params };
}

// Rewrite the value column of a parsed param file, keeping everything else
export function serializeParamFile(parsed, values) {
  const lines = [...parsed.lines];
  for (const p of parsed.params) {
    const v = values[p.name];
    if (v === undefined || v === p.value) continue;
    lines[p.line] = lines[p.line].replace(PARAM_LINE, (_, a, n, b, _v, rest) => `${a}${n}${b}${v}${rest}`);
  }
  return lines.join('\n');
}

// Parse sipnet.out (with header) into columns of Float64Arrays
export function parseOutput(text) {
  const lines = text.split('\n');
  let start = lines.findIndex((l) => /^\s*year\s+day\s+time\b/.test(l));
  let columns;
  if (start >= 0) {
    columns = lines[start].trim().split(/\s+/);
    start += 1;
  } else {
    throw new Error('sipnet.out has no header row');
  }
  const rows = lines.slice(start).filter((l) => l.trim() !== '');
  const data = columns.map(() => new Float64Array(rows.length));
  rows.forEach((row, i) => {
    const f = row.trim().split(/\s+/);
    for (let c = 0; c < columns.length; c++) data[c][i] = Number(f[c]);
  });
  return { columns, data: Object.fromEntries(columns.map((c, i) => [c, data[i]])), n: rows.length };
}

const isLeap = (y) => (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0;
const MONTH_STARTS = [0, 31, 59, 90, 120, 151, 181, 212, 243, 273, 304, 334];

// Zero-based month for a day of year
function monthOf(year, day) {
  let dd = day - 1;
  if (isLeap(year)) {
    if (day === 60) return 1;  // Feb 29
    if (day > 60) dd -= 1;
  }
  let m = 11;
  while (m > 0 && dd < MONTH_STARTS[m]) m--;
  return m;
}

// Decimal year for a (year, day-of-year, hour) triple
export const decimalYear = (y, d, h = 0) => y + (d - 1 + h / 24) / (isLeap(y) ? 366 : 365);

// Aggregate a series to day / month / year buckets with a mean or sum.
// Returns { x: decimal-year bucket midpoints, y }.
export function aggregate(out, variable, period, stat) {
  const { year, day, time } = out.data;
  const v = out.data[variable];
  if (period === 'none') {
    const x = new Float64Array(out.n);
    for (let i = 0; i < out.n; i++) x[i] = decimalYear(year[i], day[i], time[i]);
    return { x, y: v };
  }
  const xs = [];
  const ys = [];
  let key = null;
  let sum = 0;
  let count = 0;
  let mid = 0;
  const flush = () => {
    if (count) {
      xs.push(mid);
      ys.push(stat === 'sum' ? sum : sum / count);
    }
  };
  for (let i = 0; i < out.n; i++) {
    const y = year[i];
    const d = day[i];
    let k;
    let m;
    if (period === 'day') {
      k = y * 1000 + d;
      m = decimalYear(y, d, 12);
    } else if (period === 'month') {
      const mo = monthOf(y, d);
      k = y * 100 + mo;
      m = y + (mo + 0.5) / 12;
    } else {
      k = y;
      m = y + 0.5;
    }
    if (k !== key) {
      flush();
      key = k;
      sum = 0;
      count = 0;
      mid = m;
    }
    sum += v[i];
    count++;
  }
  flush();
  return { x: Float64Array.from(xs), y: Float64Array.from(ys) };
}

// Small, fast, non-cryptographic string hash (cyrb53), used to key uploads
export function hashText(str) {
  let h1 = 0xdeadbeef;
  let h2 = 0x41c6ce57;
  for (let i = 0; i < str.length; i++) {
    const ch = str.charCodeAt(i);
    h1 = Math.imul(h1 ^ ch, 2654435761);
    h2 = Math.imul(h2 ^ ch, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  return (4294967296 * (2097151 & h2) + (h1 >>> 0)).toString(16);
}
